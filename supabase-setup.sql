-- Six Degrees shared score board
-- Run this in the Supabase project's SQL Editor.

create table if not exists public.player_scores (
  id bigint generated by default as identity primary key,
  score integer not null check (score between 0 and 1000),
  hops integer not null check (hops between 1 and 500),
  elapsed_seconds integer not null check (elapsed_seconds between 0 and 86400),
  mode text not null check (mode in ('daily', 'random', 'custom')),
  start_title text not null check (char_length(start_title) between 1 and 160),
  destination_title text not null check (char_length(destination_title) between 1 and 160),
  created_at timestamptz not null default now()
);

create index if not exists player_scores_created_at_idx
  on public.player_scores (created_at desc);

alter table public.player_scores enable row level security;

-- The browser can add a score but cannot read, change, or delete individual rows.
revoke all on table public.player_scores from anon, authenticated;
grant insert (score, hops, elapsed_seconds, mode, start_title, destination_title)
  on table public.player_scores to anon;
grant usage on sequence public.player_scores_id_seq to anon;

drop policy if exists "Anyone can submit a valid game score" on public.player_scores;
create policy "Anyone can submit a valid game score"
  on public.player_scores
  for insert
  to anon
  with check (
    score between 0 and 1000
    and hops between 1 and 500
    and elapsed_seconds between 0 and 86400
    and mode in ('daily', 'random', 'custom')
    and char_length(start_title) between 1 and 160
    and char_length(destination_title) between 1 and 160
  );

-- Return only aggregate counts. The current run is excluded from its own comparison.
create or replace function public.get_score_comparison(p_score integer)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  with all_scores as materialized (
    select score from public.player_scores
  ), stats as (
    select
      count(*) as total,
      count(*) filter (where score < p_score) as lower_scores
    from all_scores
  ), bucket_counts as (
    select least(score / 100, 9) as bucket, count(*) as players
    from all_scores
    group by 1
  ), buckets as (
    select generate_series(0, 9) as bucket
  )
  select jsonb_build_object(
    'total', greatest(stats.total - 1, 0),
    'lower', stats.lower_scores,
    'bins', (
      select coalesce(
        jsonb_agg(
          jsonb_build_object(
            'bucket', buckets.bucket,
            'count', greatest(
              coalesce(bucket_counts.players, 0)
              - case when buckets.bucket = least(p_score / 100, 9) then 1 else 0 end,
              0
            )
          ) order by buckets.bucket
        ),
        '[]'::jsonb
      )
      from buckets
      left join bucket_counts using (bucket)
    )
  )
  from stats;
$$;

revoke all on function public.get_score_comparison(integer) from public, anon, authenticated;
grant execute on function public.get_score_comparison(integer) to anon;
